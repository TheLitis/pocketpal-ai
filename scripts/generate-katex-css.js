const fs = require('fs');
const path = require('path');

const source = require.resolve('katex/dist/katex.min.css');
const target = path.join(
  __dirname,
  '..',
  'src',
  'components',
  'MarkdownView',
  'katexStyles.generated.ts',
);
const katexCss = fs
  .readFileSync(source, 'utf8')
  // The WebView has a CSP that blocks every resource load. Removing the
  // packaged relative font URLs keeps rendering entirely local and makes the
  // system math/serif fallback explicit instead of producing failed requests.
  .replace(/@font-face\{[^}]*\}/g, '');
const css = `${katexCss}\n.katex,.katex *{font-family:'Cambria Math','Times New Roman',serif!important}`;

fs.writeFileSync(
  target,
  [
    '// Generated by scripts/generate-katex-css.js. Do not edit manually.',
    `export const KATEX_WEBVIEW_CSS = ${JSON.stringify(css)};`,
    '',
  ].join('\n'),
);
